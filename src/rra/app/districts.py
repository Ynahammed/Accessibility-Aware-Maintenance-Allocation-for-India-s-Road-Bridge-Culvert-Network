DISTRICTS: dict[str, DistrictSpec] = {spec.id: spec for spec in SPECS}


def get_spec(district_id: str) -> DistrictSpec:
    """Look up a district spec; raises ``KeyError`` for unknown ids."""
    try:
        return DISTRICTS[district_id]
    except KeyError:
        raise KeyError(
            f"unknown district {district_id!r}; available: {', '.join(sorted(DISTRICTS))}"
        ) from None


def _require_buildable(spec: DistrictSpec) -> None:
    if spec.status != "ready":
        raise ValueError(
            f"district {spec.id!r} is {spec.status}: {spec.description}"
        )


def build_district(district_id: str, seed: int = 0) -> District:
    """Build the routable district graph and its assets."""
    spec = get_spec(district_id)
    _require_buildable(spec)
    if spec.preset == "generic":
        district = make_district(n_junctions=24, n_habitations=14, n_structures=10, seed=seed)
    elif spec.preset == "alappuzha":
        from rra.network.alappuzha import build_alappuzha_district

        district = build_alappuzha_district(
            demand=spec.demand or "pmgsy",
            seed=seed,
            budget_crore=spec.budget_crore,
            crew_days=spec.crew_days,
        )
    elif spec.preset == "redundant":
        district = make_redundant_district(
            n_corridors=3,
            redundancy=spec.redundancy or 2,
            seed=seed,
            # class speeds come from the live register (a reply may set them)
            class_speeds=class_speeds_from_register(live_register().register),
        )
    else:  # pragma: no cover - guarded by _require_buildable
        raise ValueError(f"cannot build district preset {spec.preset!r}")
    district.budget_crore = spec.budget_crore
    district.crew_days = spec.crew_days
    return district


#: Real instances are expensive to build (a 290k-node graph, an accessibility baseline and
#: a per-failure-set Dijkstra). Cache the district and models per process, keyed by the
#: live register fingerprint so a PWD reply still takes effect; the world itself is rebuilt
#: because planning overrides its budget and crew.
_REAL_INSTANCES: dict[tuple, tuple] = {}


def _real_instance(district_id: str, seed: int, live):
    from rra.network.alappuzha import build_alappuzha_district

    spec = get_spec(district_id)
    key = (district_id, int(seed), live.fingerprint)
    if key not in _REAL_INSTANCES:
        if len(_REAL_INSTANCES) >= 4:
            _REAL_INSTANCES.clear()
        district = build_alappuzha_district(
            demand=spec.demand or "pmgsy",
            seed=seed,
            budget_crore=spec.budget_crore,
            crew_days=spec.crew_days,
        )
        models = pipeline.build_models(district, live.register, seed=seed, sor=live.sor)
        _REAL_INSTANCES[key] = (district, models)
    return _REAL_INSTANCES[key]


def build_world_models(
    district_id: str,
    seed: int = 0,
    stress_conditions: bool | None = None,
    live=None,
):
    """Return ``(district, models, world)`` for a district.

    ``stress_conditions`` starts every structure Poor (the monsoon-stress bed the E4
    experiment uses). It defaults to true for the redundant testbeds and false elsewhere.

    Models are built from the **live** register and its schedule of rates, so a validated
    PWD/RTI reply changes outage days, repair effects, prices and the emergency premium
    in every downstream plan and simulation. ``live`` is passed in only to reuse one read.
    """
    live = live if live is not None else live_register()
    spec = get_spec(district_id)
    if spec.provenance == "real-alappuzha":
        district, models = _real_instance(district_id, seed, live)
    else:
        district = build_district(district_id, seed)
        models = pipeline.build_models(district, live.register, seed=seed, sor=live.sor)
    world = pipeline.build_world(district, live.register, seed=seed)
    stress = spec.preset == "redundant" if stress_conditions is None else stress_conditions
    if stress:
        for asset in world.assets.values():
            asset.condition = 2
    return district, models, world


@lru_cache(maxsize=8)
def _read_json(path: str, mtime_ns: int) -> dict:
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def allocation_artifact(filename: str) -> dict | None:
    """A persisted allocation JSON written by ``scripts/build_alappuzha_allocation.py``.

    The mtime is part of the cache key, so a rebuild is picked up without a restart.
    """
    path = ALLOCATION_DIR / filename
    try:
        stat = path.stat()
    except OSError:
        return None
    return _read_json(str(path), stat.st_mtime_ns)


def allocation_metadata(demand: str | None) -> dict | None:
    """The persisted instance metadata, if the offline build has run.

    Reading it keeps ``/api/districts`` from loading the 290k-node graph just to count
    nodes.
    """
    if not demand:
        return None
    return allocation_artifact(f"{demand}_meta.json")


def layers_present() -> bool:
    """Whether this installation ships the real-district layer files.

    A deployment can carry the code without the multi-hundred-megabyte processed layers, so
    the registry must not advertise a real instance as ``ready`` when a plan cannot be built.
    Kept as one helper so the summary and the planner cannot disagree.
    """
    try:
        from rra.network.alappuzha import layers_available
    except Exception:  # a partial install must read as unavailable, not crash the listing
        return False
    return bool(layers_available())


def summarize(district_id: str, seed: int = 0) -> dict:
    """Counts, provenance and defaults for one district."""
    spec = get_spec(district_id)
    out = asdict(spec)
    if spec.provenance == "real-alappuzha":
        meta = allocation_metadata(spec.demand)
        if meta:
            out.update(meta.get("counts", {}))
            out["facility_types"] = ["health"]
            out["selection"] = meta.get("selection")
            out["assumed"] = meta.get("assumed")
            out["instance_built"] = True
            out["note"] = meta.get("note") or REAL_ALAPPUZHA_NOTE
        else:
            out.update(
                n_nodes=None,
                n_edges=None,
                n_habitations=None,
                n_structures=None,
                facility_types=["health"],
                assumed=dict(ALLOCATION_ASSUMED),
                instance_built=False,
            )
            out["note"] = (
                "Real Alappuzha allocation instance is not built yet; run "
                "scripts/build_alappuzha_allocation.py to persist its metadata and plans."
            )
            if not layers_present():
                # The deployed app carries the code but not the layers, so reporting "ready"
                # promised a plan the host cannot compute.
                out["status"] = "layers-missing"
                out["note"] = (
                    "This build does not include the Alappuzha network layers, so no plan can "
                    "be computed here. The same code builds it locally from the layers "
                    "listed in REPRODUCE.md."
                )
        return out
    if spec.status == "ready":
        district = build_district(district_id, seed)
        out.update(
            n_nodes=district.graph.number_of_nodes(),
            n_edges=district.graph.number_of_edges(),
            n_habitations=len(district.habitations),
            n_structures=len(district.structures),
            facility_types=sorted(district.facilities),
        )
    else:
        out.update(n_nodes=1972, n_edges=2361, n_habitations=0, n_structures=74,
                   facility_types=[])
    out["note"] = SYNTHETIC_NOTE if spec.provenance == "synthetic" else spec.description
    return out


def list_districts(seed: int = 0) -> list[dict]:
    return [summarize(spec_id, seed) for spec_id in DISTRICTS]


@lru_cache(maxsize=2)
def _osm_road_graph():
    """The downloaded Alappuzha road graph, parsed with networkx only."""
    from rra.ingest.osm import load_graphml_plain

    if not OSM_GRAPHML.exists():
        raise ValueError(
            "road graph not found at data/raw/osm/roads.graphml; "
            "run scripts/download_data.py to fetch the OSM extract"
        )
    return load_graphml_plain(OSM_GRAPHML)


def _real_network_view(spec: DistrictSpec, seed: int) -> dict:
    """A bounded map of the 30 screened structures, not the 290k-node district graph.

    The plan panel uses the allocation endpoint; this view exists so an explicit network
    request does not try to serialise the whole district graph.
    """
    from rra.network.alappuzha import road_graph, structure_portfolio

    graph = road_graph()
    records = structure_portfolio()
    nodes: dict = {}
    edges = []
    for record in records:
        u, v = record["edge_u"], record["edge_v"]
        if not graph.has_edge(u, v):
            continue
        for node in (u, v):
            if node not in nodes:
                x, y = graph.nodes[node]["pos"]
                nodes[node] = {"id": str(node), "x": float(x), "y": float(y)}
        edges.append(
            {
                "u": str(u),
                "v": str(v),
                "bridge": record["structure_type"] == "minor_bridge",
                "culvert": record["structure_type"] == "culvert",
                "length_m": float(graph.edges[u, v]["length_m"]),
                "structure": record["asset_id"],
                "candidate": record["candidate_entity_id"],
                "verified_structure": False,
            }
        )
    return {
        "ok": True,
        "district": summarize(spec.id, seed),
        "read_only": True,
        "provenance": spec.provenance,
        "source": "data/processed/alappuzha_network_join",
        "counts": {
            "nodes": graph.number_of_nodes(),
            "edges": graph.number_of_edges(),
            "bridges": sum(
                1 for record in records if record["structure_type"] == "minor_bridge"
            ),
            "culverts": sum(
                1 for record in records if record["structure_type"] == "culvert"
            ),
        },
        "nodes": list(nodes.values()),
        "edges": edges,
        "note": (
            "Bounded view of the screened portfolio only: 30 unverified road/water "
            "candidate crossings on their source edges, not the full district graph and "
            "not an asset register."
        ),
    }


def network_view(district_id: str, seed: int = 0) -> dict:
    """Read-only road-network geometry for a district, for the map.

    Deliberately carries **no allocation numbers**. The Alappuzha endpoint is a legacy
    town-area map view; district-wide population, facility, and crossing layers are
    maintained separately, and verified PWD condition/cost inputs are still unavailable.
    Only the bounded town-area geometry and its OSM bridge/culvert tags are returned.
    """
    spec = get_spec(district_id)
    if spec.provenance == "real-alappuzha":
        return _real_network_view(spec, seed)
    if spec.status != "ready":
        g = _osm_road_graph()
        bridges = sum(1 for *_, d in g.edges(data=True) if d.get("is_bridge"))
        culverts = sum(1 for *_, d in g.edges(data=True) if d.get("is_culvert"))
        return {
            "ok": True,
            "district": summarize(district_id, seed),
            "read_only": True,
            "provenance": spec.provenance,
            "source": "data/raw/osm/roads.graphml",
            "counts": {
                "nodes": g.number_of_nodes(),
                "edges": g.number_of_edges(),
                "bridges": bridges,
                "culverts": culverts,
            },
            "nodes": [
                {"id": str(n), "x": float(d["x"]), "y": float(d["y"])}
                for n, d in g.nodes(data=True)
            ],
            "edges": [
                {
                    "u": str(u),
                    "v": str(v),
                    "bridge": bool(d.get("is_bridge")),
                    "culvert": bool(d.get("is_culvert")),
                    "length_m": float(d.get("length_m", 0.0) or 0.0),
                }
                for u, v, d in g.edges(data=True)
            ],
            "note": (
                "Read-only legacy town-area OpenStreetMap graph: geometry and bridge/culvert "
                "tags only. District-wide Census/PMGSY, facility, and crossing layers are "
                "maintained separately; verified PWD condition/cost inputs are unavailable, "
                "so no accessibility loss, spend, or recommendation is computed here."
            ),
        }

    district = build_district(district_id, seed)
    g = district.graph
    return {
        "ok": True,
        "district": summarize(district_id, seed),
        "read_only": False,
        "provenance": spec.provenance,
        "source": "rra.network.synthetic",
        "counts": {"nodes": g.number_of_nodes(), "edges": g.number_of_edges()},
        "nodes": [
            {
                "id": str(n),
                "x": float(d.get("pos", (0.0, 0.0))[0]),
                "y": float(d.get("pos", (0.0, 0.0))[1]),
            }
            for n, d in g.nodes(data=True)
        ],
        "edges": [
            {"u": str(u), "v": str(v), "bridge": False, "culvert": False, "length_m": 0.0}
            for u, v in g.edges()
        ],
        "note": "Geometric view only; use the plan endpoint for the allocation.",
    }


def assets_payload(district_id: str, seed: int = 0) -> dict:
    """Per-structure service state, with the accessibility loss of failing it alone."""
    spec = get_spec(district_id)
    _require_buildable(spec)
    district, models, world = build_world_models(district_id, seed)
    rows = []
    for asset in world.assets.values():
        rows.append(
            {
                "id": asset.asset_id,
                "type": asset.structure_type,
                "node": str(asset.node),
                "condition": int(asset.condition),
                "state": STATES[int(asset.condition)],
                "age": int(asset.age),
                "solo_loss": float(models.acc.loss(failed_nodes=[asset.node])),
                "outage_days": models.outage(asset),
                "corridor": (
                    int(asset.asset_id.lstrip("S")) // spec.redundancy
                    if spec.redundancy
                    else None
                ),
                "provenance": district.asset_provenance.get(asset.asset_id),
            }
        )
    rows.sort(key=lambda r: (r["corridor"] if r["corridor"] is not None else 0, r["id"]))
    payload = {
        "ok": True,
        "district": summarize(district_id, seed),
        "seed": seed,
        "assets": rows,
    }
    if spec.provenance == "real-alappuzha":
        payload.update(
            demand_profile=spec.demand,
            screening=SELECTION_NOTE,
            assumed=dict(ALLOCATION_ASSUMED),
            scenario_stress=0.0,
            scenario_sigma=0.4,
        )
    return payload
