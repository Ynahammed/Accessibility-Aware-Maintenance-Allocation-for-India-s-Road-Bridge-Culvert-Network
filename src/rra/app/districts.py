"""Study-district registry.

The app ships **seeded synthetic districts** for method comparisons and **real Alappuzha
allocation instances** built from the public road graph, PMGSY/Census demand and mapped OSM
hospitals. Provenance is carried in every payload: on the real instances the 30 structures
are unverified road/water screening candidates and condition, age, outage and cost are
assumed. No output is a real-district condition finding or spending recommendation.

The read-only map endpoint remains a bounded view of the screened portfolio; the full
district graph and spatial joins are documented in the processed evidence files.
"""

