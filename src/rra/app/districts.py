DISTRICTS: dict[str, DistrictSpec] = {spec.id: spec for spec in SPECS}


def get_spec(district_id: str) -> DistrictSpec:
    """Look up a district spec; raises ``KeyError`` for unknown ids."""
    try:
        return DISTRICTS[district_id]
    except KeyError:
        raise KeyError(
            f"unknown district {district_id!r}; available: {', '.join(sorted(DISTRICTS))}"
        ) from None


def _require_buildable(spec: DistrictSpec) -> None:
    if spec.status != "ready":
        raise ValueError(
            f"district {spec.id!r} is {spec.status}: {spec.description}"
        )


def build_district(district_id: str, seed: int = 0) -> District:
    """Build the routable district graph and its assets."""
    spec = get_spec(district_id)
    _require_buildable(spec)
    if spec.preset == "generic":
        district = make_district(n_junctions=24, n_habitations=14, n_structures=10, seed=seed)
    elif spec.preset == "redundant":
        district = make_redundant_district(
            n_corridors=3,
            redundancy=spec.redundancy or 2,
            seed=seed,
            # class speeds come from the live register (a reply may set them)
            class_speeds=class_speeds_from_register(live_register().register),
        )
    else:  # pragma: no cover - guarded by _require_buildable
        raise ValueError(f"cannot build district preset {spec.preset!r}")
    district.budget_crore = spec.budget_crore
    district.crew_days = spec.crew_days
    return district


def build_world_models(
    district_id: str,
    seed: int = 0,
    stress_conditions: bool | None = None,
    live=None,
):
    """Return ``(district, models, world)`` for a district.

    ``stress_conditions`` starts every structure Poor (the monsoon-stress bed the E4
    experiment uses). It defaults to true for the redundant testbeds and false elsewhere.

    Models are built from the **live** register and its schedule of rates, so a validated
    PWD/RTI reply changes outage days, repair effects, prices and the emergency premium
    in every downstream plan and simulation. ``live`` is passed in only to reuse one read.
    """
    live = live if live is not None else live_register()
    spec = get_spec(district_id)
    district = build_district(district_id, seed)
    models = pipeline.build_models(district, live.register, seed=seed, sor=live.sor)
    world = pipeline.build_world(district, live.register, seed=seed)
    stress = spec.preset == "redundant" if stress_conditions is None else stress_conditions
    if stress:
        for asset in world.assets.values():
            asset.condition = 2
    return district, models, world


def summarize(district_id: str, seed: int = 0) -> dict:
    """Counts, provenance and defaults for one district."""
    spec = get_spec(district_id)
    out = asdict(spec)
    if spec.status == "ready":
        district = build_district(district_id, seed)
        out.update(
            n_nodes=district.graph.number_of_nodes(),
            n_edges=district.graph.number_of_edges(),
            n_habitations=len(district.habitations),
            n_structures=len(district.structures),
            facility_types=sorted(district.facilities),
        )
    else:
        out.update(n_nodes=1972, n_edges=2361, n_habitations=0, n_structures=74,
                   facility_types=[])
    out["note"] = SYNTHETIC_NOTE if spec.provenance == "synthetic" else spec.description
    return out


def list_districts(seed: int = 0) -> list[dict]:
    return [summarize(spec_id, seed) for spec_id in DISTRICTS]


@lru_cache(maxsize=2)
def _osm_road_graph():
    """The downloaded Alappuzha road graph, parsed with networkx only."""
    from rra.ingest.osm import load_graphml_plain

    if not OSM_GRAPHML.exists():
        raise ValueError(
            "road graph not found at data/raw/osm/roads.graphml; "
            "run scripts/download_data.py to fetch the OSM extract"
        )
    return load_graphml_plain(OSM_GRAPHML)


def network_view(district_id: str, seed: int = 0) -> dict:
    """Read-only road-network geometry for a district, for the map.

    Deliberately carries **no allocation numbers**. The Alappuzha endpoint is a legacy
    town-area map view; district-wide population, facility, and crossing layers are
    maintained separately, and verified PWD condition/cost inputs are still unavailable.
    Only the bounded town-area geometry and its OSM bridge/culvert tags are returned.
    """
    spec = get_spec(district_id)
    if spec.status != "ready":
        g = _osm_road_graph()
        bridges = sum(1 for *_, d in g.edges(data=True) if d.get("is_bridge"))
        culverts = sum(1 for *_, d in g.edges(data=True) if d.get("is_culvert"))
        return {
            "ok": True,
            "district": summarize(district_id, seed),
            "read_only": True,
            "provenance": spec.provenance,
            "source": "data/raw/osm/roads.graphml",
            "counts": {
                "nodes": g.number_of_nodes(),
                "edges": g.number_of_edges(),
                "bridges": bridges,
                "culverts": culverts,
            },
            "nodes": [
                {"id": str(n), "x": float(d["x"]), "y": float(d["y"])}
                for n, d in g.nodes(data=True)
            ],
            "edges": [
                {
                    "u": str(u),
                    "v": str(v),
                    "bridge": bool(d.get("is_bridge")),
                    "culvert": bool(d.get("is_culvert")),
                    "length_m": float(d.get("length_m", 0.0) or 0.0),
                }
                for u, v, d in g.edges(data=True)
            ],
            "note": (
                "Read-only legacy town-area OpenStreetMap graph: geometry and bridge/culvert "
                "tags only. District-wide Census/PMGSY, facility, and crossing layers are "
                "maintained separately; verified PWD condition/cost inputs are unavailable, "
                "so no accessibility loss, spend, or recommendation is computed here."
            ),
        }

    district = build_district(district_id, seed)
    g = district.graph
    return {
        "ok": True,
        "district": summarize(district_id, seed),
        "read_only": False,
        "provenance": spec.provenance,
        "source": "rra.network.synthetic",
        "counts": {"nodes": g.number_of_nodes(), "edges": g.number_of_edges()},
        "nodes": [
            {
                "id": str(n),
                "x": float(d.get("pos", (0.0, 0.0))[0]),
                "y": float(d.get("pos", (0.0, 0.0))[1]),
            }
            for n, d in g.nodes(data=True)
        ],
        "edges": [
            {"u": str(u), "v": str(v), "bridge": False, "culvert": False, "length_m": 0.0}
            for u, v in g.edges()
        ],
        "note": "Geometric view only; use the plan endpoint for the allocation.",
    }


def assets_payload(district_id: str, seed: int = 0) -> dict:
    """Per-structure service state, with the accessibility loss of failing it alone."""
    spec = get_spec(district_id)
    _require_buildable(spec)
    district, models, world = build_world_models(district_id, seed)
    rows = []
    for asset in world.assets.values():
        rows.append(
            {
                "id": asset.asset_id,
                "type": asset.structure_type,
                "node": str(asset.node),
                "condition": int(asset.condition),
                "state": STATES[int(asset.condition)],
                "age": int(asset.age),
                "solo_loss": float(models.acc.loss(failed_nodes=[asset.node])),
                "outage_days": models.outage(asset),
                "corridor": (
                    int(asset.asset_id.lstrip("S")) // spec.redundancy
                    if spec.redundancy
                    else None
                ),
            }
        )
    rows.sort(key=lambda r: (r["corridor"] if r["corridor"] is not None else 0, r["id"]))
    return {
        "ok": True,
        "district": summarize(district_id, seed),
        "seed": seed,
        "assets": rows,
    }
