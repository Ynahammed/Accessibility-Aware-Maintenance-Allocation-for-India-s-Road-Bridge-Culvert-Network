"""Study-district registry.

The app ships **seeded synthetic allocation districts**, labelled by provenance in the
dashboard, API payloads, and docs. Alappuzha Census/PMGSY, OSM road/facility, and crossing
layers are available in the evidence base, but are not allocation-model inputs: verified
PWD asset condition and maintenance-cost records remain unavailable. Nothing in the
synthetic allocation results should be read as a real-district recommendation.

The read-only map endpoint below remains a legacy town-area OSM view; the district-wide
network and spatial joins are documented separately in the processed evidence files.
"""

