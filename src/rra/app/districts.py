    name: str
    preset: str  # "generic" | "redundant"
    provenance: str  # "synthetic" | "real-osm" | ...
    description: str
    budget_crore: float
    crew_days: float
    redundancy: int | None = None
    status: str = "ready"  # "ready" | "network-only" | "blocked"


