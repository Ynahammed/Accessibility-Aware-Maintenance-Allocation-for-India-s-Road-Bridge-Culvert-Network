_EVIDENCE_CACHE: dict | None = None
_EVIDENCE_LOCK = threading.Lock()


def _read_json(rel: str):
    path = ROOT / rel
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def _read_text(rel: str):
    try:
        return (ROOT / rel).read_text(encoding="utf-8")
    except OSError:
        return None


def load_evidence() -> dict:
    """Load the **frozen** result files (they only change when a script is re-run).

    The assumptions register is deliberately excluded: it is live (a validated PWD/RTI
    reply changes it) and is attached per request by :func:`get_evidence`.
    """
    return {
        "ok": True,
        "scope": "Indian data only; US NBI deterioration results (E1) are archived, not active evidence",
        "access_baseline": _read_json("data/processed/alappuzha_access_baseline/summary.json"),
        "flood_exposure": _read_json("data/processed/alappuzha_flood_exposure/summary.json"),
        "resilience": _read_json("data/processed/alappuzha_resilience/summary.json"),
        "population_reconcile": _read_json("data/processed/alappuzha_population_reconcile/summary.json"),
        "e3_allocation": _read_json("experiments/e03_allocation/results.json"),
        "e4_network_effects": _read_json("experiments/e04_network_effects/results.json"),
        "e8_robustness": _read_json("experiments/e08_robustness/results.json"),
        "osm_qa": _read_text("data/processed/osm_qa.md"),
        "real_district_qa": _read_text("data/processed/real_district_qa.md"),
        "data_matrix": DATA_MATRIX,
        **_live_fields(),
    }


def _live_fields() -> dict:
    """The register fields any evidence payload must carry (live, never frozen).

    ``register_markdown`` is rendered from the live register rather than read from the
    generated ``docs/assumptions.md``: that file describes the *default* register, so
    serving it alongside measured values showed two different tables for one payload.
    """
    live = live_register()
    return {
        "assumptions": live.register.as_dict(),
        "assumption_overrides": live.applied,
        "assumptions_source": live.describe(),
        # a partly refused reply must be visible, not silently absent from the panel
        "refused": list(live.refused),
        "coverage_warnings": list(live.coverage_warnings),
        "register_markdown": live.markdown(),
    }


def get_evidence() -> dict:
    """Frozen evidence from cache, plus the live assumptions register.

    Only the register is re-resolved per request (one ``stat`` when the reply file is
    unchanged), so re-running the loader is picked up without restarting the server while
    the experiment results stay cached.
    """
    global _EVIDENCE_CACHE
    with _EVIDENCE_LOCK:
        if _EVIDENCE_CACHE is None:
            _EVIDENCE_CACHE = load_evidence()
        # Re-resolve only the register fields; the frozen results stay cached.
        return {**_EVIDENCE_CACHE, **_live_fields()}
